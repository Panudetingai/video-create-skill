#!/usr/bin/env node
// Pull the exact icons Mali-Cowork uses out of its node_modules:
//  - lucide-react icon nodes (UI glyphs)
//  - @lobehub/icons brand marks (providers, CLIs, connectors)
// and write them to src/vendor/icons.js as plain SVG strings.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const app = process.argv[2] || join(root, '..', 'Mali-Cowork');
const nm = join(app, 'node_modules');

const LUCIDE = [
  'square-pen', 'sparkles', 'code', 'code-xml', 'images', 'layout-grid', 'search', 'chevron-right', 'chevron-down',
  'inbox', 'files', 'chart-column', 'folder', 'folder-open', 'folder-lock', 'settings-2', 'globe', 'moon', 'minus', 'square',
  'x', 'plus', 'mic', 'arrow-up', 'message-square', 'users', 'terminal', 'lock', 'shield-check', 'monitor', 'undo-2',
  'hard-drive', 'git-branch', 'key-round', 'file-text', 'file-plus', 'file-pen', 'file-minus', 'clock', 'coins',
  'calculator', 'check', 'circle-check', 'loader', 'hand', 'circle-dashed', 'mail', 'package', 'book-open', 'command',
  'scan', 'copy', 'clipboard-paste', 'external-link', 'maximize', 'zap', 'trophy', 'swords', 'download', 'key',
  'rocket', 'image', 'file-code', 'calendar', 'receipt', 'eye', 'bell', 'triangle-alert', 'sun-moon', 'languages',
  'messages-square', 'folder-kanban', 'book', 'info', 'scroll-text', 'wand-sparkles', 'plug', 'plug-zap', 'refresh-cw',
  'arrow-right', 'party-popper', 'audio-lines', 'apple', 'laptop', 'git-compare', 'server-off', 'wifi-off', 'play',
  'file-spreadsheet', 'file-image', 'bug', 'circle-alert', 'mouse-pointer-2', 'panel-left',
];
const LOBE = ['OpenAI', 'Anthropic', 'Claude', 'Google', 'Gemini', 'Groq', 'DeepSeek', 'Ollama', 'OpenCode', 'Codex',
  'Cursor', 'Notion', 'Figma', 'Microsoft', 'Apple', 'GithubCopilot', 'Github'];

function lucide(name) {
  const file = join(nm, 'lucide-react/dist/esm/icons', name + '.mjs');
  if (!existsSync(file)) return null;
  const src = readFileSync(file, 'utf8');
  const m = /const __iconData = (\{[\s\S]*?\n\});\n/.exec(src);
  if (!m) return null;
  const node = Function('return ' + m[1])().node;
  return node.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key')
    .map(([k, v]) => `${k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())}="${v}"`).join(' ')}/>`).join('');
}

// Rebuild an SVG from the transpiled JSX (fill/fillRule/d/etc on path/circle/rect elements).
function lobe(name, variant) {
  const file = join(nm, '@lobehub/icons/es', name, 'components', variant + '.js');
  if (!existsSync(file)) return null;
  const src = readFileSync(file, 'utf8');
  const vb = /viewBox: "([^"]+)"/.exec(src)?.[1] || '0 0 24 24';
  const defs = [];
  const els = [];
  const re = /_jsxs?\("(path|circle|rect|ellipse|stop|linearGradient|radialGradient|defs|g)", \{([\s\S]*?)\}\)/g;
  let m;
  while ((m = re.exec(src))) {
    const [, tag, body] = m;
    if (!['path', 'circle', 'rect', 'ellipse'].includes(tag)) continue;
    const attrs = [];
    for (const a of body.matchAll(/(\w+): ("[^"]*"|[\d.]+)/g)) {
      const k = a[1]; let v = a[2].replace(/^"|"$/g, '');
      if (k === 'children' || k === 'key' || k === 'style') continue;
      if (/^fill|^stroke/.test(k) && /^url\(#/.test(v)) v = 'currentColor';
      attrs.push(`${k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())}="${v}"`);
    }
    // gradient ids are generated at runtime (a.fill) -> fall back to currentColor
    if (/fill: [a-z]\.fill|fill: "url/.test(body) && !attrs.some((x) => x.startsWith('fill='))) attrs.push('fill="currentColor"');
    els.push(`<${tag} ${attrs.join(' ')}/>`);
  }
  if (!els.length) return null;
  return { vb, svg: els.join(''), defs: defs.join('') };
}

const colorOf = (name) => {
  const f = join(nm, '@lobehub/icons/es', name, 'style.js');
  if (!existsSync(f)) return null;
  return /COLOR_PRIMARY = '([^']+)'/.exec(readFileSync(f, 'utf8'))?.[1] ?? null;
};

const L = {};
for (const n of LUCIDE) { const s = lucide(n); if (s) L[n] = s; else console.warn('lucide missing:', n); }
const B = {};
for (const n of LOBE) {
  const mono = lobe(n, 'Mono');
  if (!mono) { console.warn('lobe missing:', n); continue; }
  B[n] = { vb: mono.vb, mono: mono.svg, brand: colorOf(n) };
}
const out = `// AUTO-GENERATED by tools/extract-icons.mjs (lucide-react + @lobehub/icons from Mali-Cowork)
export const LUCIDE = ${JSON.stringify(L, null, 0)};
export const BRANDS = ${JSON.stringify(B, null, 0)};
`;
writeFileSync(join(root, 'src/vendor/icons.js'), out);
console.log(`icons.js: ${Object.keys(L).length} lucide, ${Object.keys(B).length} brands`);
