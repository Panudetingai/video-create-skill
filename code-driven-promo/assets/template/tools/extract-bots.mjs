#!/usr/bin/env node
// Copy the CoworkBot engine out of Mali-Cowork (public/anim/cowork-bots.html)
// into an ES module, untouched: presets, SVG rig, springs, states and habits.
// Only the page's own rAF loop / demo / page setup are left out — the promo
// engine drives `bot.update(dt, f)` itself on a virtual clock.
//
//   node tools/extract-bots.mjs [path/to/Mali-Cowork]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const app = process.argv[2] || join(root, '..', 'Mali-Cowork');
const html = readFileSync(join(app, 'public/anim/cowork-bots.html'), 'utf8');

const start = html.indexOf('var TAU = Math.PI * 2;');
const end = html.indexOf('// ---------- shared animation loop ----------');
if (start < 0 || end < 0) throw new Error('cowork-bots.html layout changed: markers not found');

const body = html.slice(start, end).replace(/\n  /g, '\n');
const out = `// AUTO-GENERATED by tools/extract-bots.mjs from Mali-Cowork/public/anim/cowork-bots.html
// Do not edit by hand — re-run \`npm run sync:bots\` after the app's bots change.
/* eslint-disable */
// Deterministic time + randomness for the promo (module-scoped shadows):
import { vt } from '../engine/clock.js';
const { setTimeout, clearTimeout, setInterval, clearInterval, Math } = vt;
${body}
export { createBot, PRESETS, LABELS, RING_COLORS };
`;
mkdirSync(join(root, 'src/vendor'), { recursive: true });
writeFileSync(join(root, 'src/vendor/cowork-bots.js'), out);
console.log(`cowork-bots.js: ${out.length} bytes (from ${app})`);
